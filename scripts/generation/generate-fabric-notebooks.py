def _write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=1, ensure_ascii=False)
        handle.write("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "Validate the notebooks the generator would emit without writing"
            " them; useful for CI."
        ),
    )
    args = parser.parse_args(argv)

    artifacts: list[tuple[Path, dict[str, Any], str]] = [
        (
            NOTEBOOK_DIR / "silver-scd2-merge-template.ipynb",
            build_scd2_merge_notebook(),
            "silver-scd2-merge-template",
        ),
        (
            NOTEBOOK_DIR / "silver-append-template.ipynb",
            build_append_notebook(),
            "silver-append-template",
        ),
        (
            NOTEBOOK_DIR / "silver-codeset-load-template.ipynb",
            build_codeset_notebook(),
            "silver-codeset-load-template",
        ),
    ]

    for _, notebook, label in artifacts:
        validate_notebook(notebook, label)

    binding = build_lakehouse_binding()

    if args.check:
        print(f"Validated {len(artifacts)} notebook(s); not written (--check).")
        return 0

    for path, notebook, _ in artifacts:
        _write_json(path, notebook)
        rel = path.relative_to(ROOT).as_posix()
        cell_count = len(notebook["cells"])
        code_count = sum(1 for c in notebook["cells"] if c["cell_type"] == "code")
        print(f"Emitted {rel}: {cell_count} cells ({code_count} code).")

    binding_path = NOTEBOOK_DIR / "lakehouse-binding-template.json"
    _write_json(binding_path, binding)
    print(f"Emitted {binding_path.relative_to(ROOT).as_posix()}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
