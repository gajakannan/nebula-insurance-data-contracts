def _split_lines(source: str) -> list[str]:
    """Notebook JSON stores cell `source` as a list of lines, each ending in
    `\\n` except the last. The generator owns the canonical splitting so the
    emitted JSON is stable across reruns.
    """
    text = source.rstrip("\n")
    lines = text.split("\n")
    return [line + "\n" for line in lines[:-1]] + [lines[-1]]


def code_cell(
    source: str,
    *,
    parameters: bool = False,
) -> dict[str, Any]:
    metadata: dict[str, Any] = {}
    if parameters:
        metadata["tags"] = ["parameters"]
    return {
        "cell_type": "code",
        "metadata": metadata,
        "source": _split_lines(source),
        "outputs": [],
        "execution_count": None,
    }


def md_cell(source: str) -> dict[str, Any]:
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": _split_lines(source),
    }


def notebook_metadata(template_name: str) -> dict[str, Any]:
    return {
        "kernelspec": {
            "display_name": "Synapse PySpark",
            "language": "python",
            "name": "synapse_pyspark",
        },
        "language_info": {"name": "python"},
        "dependencies": {
            "lakehouse": {
                "default_lakehouse": "",
                "default_lakehouse_name": "",
                "default_lakehouse_workspace_id": "",
            }
        },
        "nebula": {
            "templateName": template_name,
            "templateVersion": TEMPLATE_VERSION,
            "generatorVersion": GENERATOR_VERSION,
            "doNotEdit": (
                "Generated by scripts/generation/generate-fabric-notebooks.py."
                " Edit the generator, never this file."
            ),
        },
    }


def wrap_notebook(
    template_name: str, cells: list[dict[str, Any]]
) -> dict[str, Any]:
    return {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": notebook_metadata(template_name),
        "cells": cells,
    }


