#!/usr/bin/env python3
"""Generate Fabric notebook templates for the canonical Silver layer.

Three parameterized notebooks plus a lakehouse-binding companion file land under
``targets/fabric/notebooks/``:

- ``silver-scd2-merge-template.ipynb`` drives every entity contract (the
  ``contractKind: entity`` set, including the codeset-shaped reference-data
  entities when used through their merge path).
- ``silver-append-template.ipynb`` drives every event and transaction contract.
- ``silver-codeset-load-template.ipynb`` drives codeset loads with full-refresh
  by default and incremental opt-in.
- ``lakehouse-binding-template.json`` ships with empty workspace IDs; the
  deployer fills them at deployment time.

Each notebook reads the manifest path as a parameter and adapts to any contract
of the relevant kind. The notebook code is held as multi-line strings in this
generator so that runtime logic lives in one tracked place; per-contract
notebooks are never authored.

The generator validates its own output against the Fabric ``.ipynb`` shape
inherited from ``microsoft/skills-for-fabric``: every code cell must carry
``"outputs": []`` and ``"execution_count": null``, and the notebook metadata
must include ``metadata.dependencies.lakehouse`` with empty
``default_lakehouse``, ``default_lakehouse_name``, and
``default_lakehouse_workspace_id`` slots. A failure of those rules in the
emitted JSON is a generator bug, not a runtime concern.

Authoritative spec: ``targets/fabric/conventions.md`` §9, plan
``planning-mds/FABRIC_IMPLEMENTATION_PLAN.md`` §10 / §15.4 / §17 (F6).
"""

