    metadata = notebook.get("metadata") or {}
    deps = metadata.get("dependencies") or {}
    lakehouse = deps.get("lakehouse") or {}
    for key in ("default_lakehouse", "default_lakehouse_name", "default_lakehouse_workspace_id"):
        if key not in lakehouse or lakehouse[key] != "":
            raise ValueError(
                f"{label}: metadata.dependencies.lakehouse.{key} must be empty string"
            )

    parameter_cells = 0
    for index, cell in enumerate(notebook["cells"]):
        cell_type = cell.get("cell_type")
        if cell_type == "code":
            if cell.get("outputs") != []:
                raise ValueError(
                    f"{label}: code cell {index} must have outputs == []"
                )
            if cell.get("execution_count") is not None:
                raise ValueError(
                    f"{label}: code cell {index} must have execution_count is None"
                )
            tags = (cell.get("metadata") or {}).get("tags") or []
            if "parameters" in tags:
                parameter_cells += 1
        elif cell_type == "markdown":
            if not cell.get("source"):
                raise ValueError(f"{label}: markdown cell {index} is empty")
        else:
            raise ValueError(f"{label}: cell {index} has unknown cell_type {cell_type!r}")
    if parameter_cells != 1:
        raise ValueError(
            f"{label}: expected exactly 1 cell tagged 'parameters', got {parameter_cells}"
        )


